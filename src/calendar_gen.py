"""
UniRadar Calendar Generator (.ics)
Generates standard RFC 5545 iCalendar files for 1-click import into Google Calendar, Outlook, and Apple Calendar.
"""

from __future__ import annotations
import os
from datetime import datetime, timedelta, timezone
from typing import Optional, Union

try:
    from icalendar import Calendar, Event, Alarm
    ICALENDAR_AVAILABLE = True
except ImportError:
    ICALENDAR_AVAILABLE = False

from src.models import Announcement


def _format_datetime_utc(dt: datetime) -> str:
    """Formats datetime to ICS UTC string format."""
    return dt.strftime("%Y%m%dT%H%M%SZ")


def generate_ics_content(announcement: Announcement) -> str:
    """
    Generates a compliant RFC 5545 iCalendar text representation for an announcement.
    Uses icalendar library if available, with robust RFC 5545 fallback generator.
    """
    if ICALENDAR_AVAILABLE:
        cal = Calendar()
        cal.add("prodid", "-//UniRadar UM6P Campus Engine//EN")
        cal.add("version", "2.0")
        cal.add("calscale", "GREGORIAN")
        cal.add("method", "PUBLISH")

        event = Event()
        event.add("summary", announcement.title)
        event.add("uid", f"uniradar-{announcement.id}@um6p.ma")
        event.add("dtstamp", datetime.now(timezone.utc))
        event.add("dtstart", announcement.start_datetime)

        if announcement.end_datetime:
            event.add("dtend", announcement.end_datetime)
        else:
            event.add("dtend", announcement.start_datetime + timedelta(hours=2))

        loc = f"{announcement.venue} ({announcement.campus} Campus)"
        if announcement.is_virtual and announcement.virtual_link:
            loc += f" | Online: {announcement.virtual_link}"
        event.add("location", loc)

        desc = (
            f"{announcement.description}\n\n"
            f"Organizer: {announcement.organizer}\n"
            f"Campus: {announcement.campus}\n"
            f"Venue: {announcement.venue}\n"
            f"Source: {announcement.source_channel or announcement.source_type}\n"
        )
        if announcement.registration_url:
            desc += f"\nRegistration / Link: {announcement.registration_url}"
        if announcement.virtual_link:
            desc += f"\nVirtual Meeting: {announcement.virtual_link}"
        desc += "\n\nGenerated by UniRadar - UM6P Anti-Chaos Campus Engine."

        event.add("description", desc)
        if announcement.registration_url:
            event.add("url", announcement.registration_url)
        event.add("status", "CONFIRMED")

        # Add 2-hour reminder alarm
        alarm = Alarm()
        alarm.add("action", "DISPLAY")
        alarm.add("description", f"Reminder: {announcement.title}")
        alarm.add("trigger", timedelta(hours=-2))
        event.add_component(alarm)

        cal.add_component(event)
        return cal.to_ical().decode("utf-8")

    # Pure Python RFC 5545 Fallback
    dt_now = _format_datetime_utc(datetime.now(timezone.utc))
    dt_start = _format_datetime_utc(announcement.start_datetime)
    dt_end = (
        _format_datetime_utc(announcement.end_datetime)
        if announcement.end_datetime
        else _format_datetime_utc(announcement.start_datetime + timedelta(hours=2))
    )

    clean_summary = announcement.title.replace("\n", " ").strip()
    clean_venue = f"{announcement.venue} ({announcement.campus} Campus)"
    clean_desc = (
        f"{announcement.description}\\n\\n"
        f"Organizer: {announcement.organizer}\\n"
        f"Campus: {announcement.campus} - {clean_venue}\\n"
        f"Registration: {announcement.registration_url or 'N/A'}\\n"
        f"Powered by UniRadar"
    ).replace("\r", "")

    ics_lines = [
        "BEGIN:VCALENDAR",
        "VERSION:2.0",
        "PRODID:-//UniRadar UM6P Campus Engine//EN",
        "CALSCALE:GREGORIAN",
        "METHOD:PUBLISH",
        "BEGIN:VEVENT",
        f"UID:uniradar-{announcement.id}@um6p.ma",
        f"DTSTAMP:{dt_now}",
        f"DTSTART:{dt_start}",
        f"DTEND:{dt_end}",
        f"SUMMARY:{clean_summary}",
        f"LOCATION:{clean_venue}",
        f"DESCRIPTION:{clean_desc}",
        f"STATUS:CONFIRMED",
        "BEGIN:VALARM",
        "ACTION:DISPLAY",
        f"DESCRIPTION:Reminder: {clean_summary}",
        "TRIGGER:-PT2H",
        "END:VALARM",
        "END:VEVENT",
        "END:VCALENDAR",
    ]
    return "\r\n".join(ics_lines) + "\r\n"


def generate_ics_bytes(announcement: Announcement) -> bytes:
    """Returns .ics content as UTF-8 encoded bytes for browser download."""
    return generate_ics_content(announcement).encode("utf-8")


def save_ics_file(announcement: Announcement, output_dir: str = "data/calendars") -> str:
    """Saves the .ics file to disk and returns the relative filepath."""
    os.makedirs(output_dir, exist_ok=True)
    filename = f"{announcement.id}_{announcement.title[:25].lower().replace(' ', '_')}.ics"
    # sanitize filename
    clean_filename = "".join(c for c in filename if c.isalnum() or c in ("_", "-", ".")).strip()
    filepath = os.path.join(output_dir, clean_filename)
    with open(filepath, "w", encoding="utf-8") as f:
        f.write(generate_ics_content(announcement))
    return filepath
